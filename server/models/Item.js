const mongoose = require('mongoose');

/**
 * Subdocument Schema for Community Location Suggestions
 *
 * FRONTEND COMPATIBILITY:
 * The frontend (js/state.js and js/app.js) provides a human-readable display name string
 * for `suggestedBy` (e.g. "Akshaya Ramesh" or fallback "Fellow Student").
 * To prevent Mongoose CastErrors when non-ObjectId strings are passed, `suggestedBy` is
 * stored as a String, and an optional `suggestedByUser` ObjectId reference is provided
 * for relational linking when the student is authenticated.
 */
const locationSuggestionSchema = new mongoose.Schema(
  {
    newLocation: {
      type: String,
      required: [true, 'New location building is required'],
      trim: true
    },
    specificSpot: {
      type: String,
      trim: true,
      default: ''
    },
    note: {
      type: String,
      trim: true,
      default: ''
    },
    suggestedBy: {
      type: String,
      trim: true,
      default: 'Fellow Student'
    },
    suggestedByUser: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null
    },
    status: {
      type: String,
      enum: {
        values: ['pending', 'verified', 'declined'],
        message: '{VALUE} is not a valid suggestion status. Allowed: pending, verified, declined'
      },
      default: 'pending'
    },
    createdAt: {
      type: Date,
      default: Date.now
    }
  },
  { _id: true }
);

/**
 * Item Model Schema — InSearch Sai University
 * Represents both Lost and Found reports with compulsory photograph validation.
 *
 * PERFORMANCE NOTE FOR PHASE 4:
 * The `image` field supports both HTTP(S) image URLs and Base64 image Data URIs
 * (as generated by FileReader in js/app.js).
 * To prevent severe network bottlenecks, Phase 4 list endpoints (GET /api/items)
 * must project/paginate appropriately or exclude massive raw Base64 strings from
 * bulk catalog feeds.
 */
const itemSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: [true, 'Item title is required'],
      trim: true,
      minlength: [2, 'Item title must be at least 2 characters'],
      maxlength: [150, 'Item title cannot exceed 150 characters']
    },
    type: {
      type: String,
      required: [true, 'Report type is required (lost or found)'],
      enum: {
        values: ['lost', 'found'],
        message: '{VALUE} is not a valid report type. Allowed: lost, found'
      },
      lowercase: true,
      trim: true
    },
    category: {
      type: String,
      required: [true, 'Category is required'],
      trim: true,
      maxlength: [80, 'Category cannot exceed 80 characters']
    },
    location: {
      type: String,
      required: [true, 'Campus building or area is required'],
      trim: true,
      maxlength: [120, 'Location cannot exceed 120 characters']
    },
    specificLocation: {
      type: String,
      trim: true,
      default: '',
      maxlength: [200, 'Specific location cannot exceed 200 characters']
    },
    previousLocation: {
      type: String,
      trim: true,
      default: ''
    },
    date: {
      type: Date,
      required: [true, 'Date of occurrence is required']
    },
    description: {
      type: String,
      required: [true, 'Item description and identifying details are required'],
      trim: true,
      minlength: [5, 'Description must be at least 5 characters'],
      maxlength: [3000, 'Description cannot exceed 3000 characters']
    },
    image: {
      type: String,
      required: [true, 'Compulsory photograph is required for verification'],
      validate: {
        validator: function (v) {
          if (!v || typeof v !== 'string') return false;
          // Validates HTTP(S) URL or Base64 Image Data URI
          const isUrl = /^https?:\/\/.+/i.test(v);
          const isDataUri = /^data:image\/(jpeg|png|webp|gif|jpg);base64,[A-Za-z0-9+/=]+/i.test(v);
          return isUrl || isDataUri;
        },
        message: 'Item image must be a valid HTTP(S) URL or Base64 image Data URI'
      }
    },
    status: {
      type: String,
      enum: {
        values: ['open', 'claimed', 'recovered'],
        message: '{VALUE} is not a valid item status. Allowed: open, claimed, recovered'
      },
      default: 'open'
    },
    reportedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User who reported this item is required']
    },
    locationSuggestions: [locationSuggestionSchema]
  },
  {
    timestamps: true,
    toJSON: { virtuals: true },
    toObject: { virtuals: true }
  }
);

// Indexes for high-performance search and filtering
itemSchema.index({ title: 'text', description: 'text', specificLocation: 'text' });
itemSchema.index({ type: 1, status: 1 });
itemSchema.index({ category: 1 });
itemSchema.index({ location: 1 });
itemSchema.index({ reportedBy: 1 });
itemSchema.index({ createdAt: -1 });

module.exports = mongoose.models.Item || mongoose.model('Item', itemSchema);
